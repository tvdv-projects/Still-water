// Cache busting without a build step.
//
// Browsers (Bluefy in particular) keep JavaScript modules cached even after the page itself is
// refreshed, so a new deploy could run with old code. This script writes an import map into
// index.html that gives every module a content hash (?v=…). When a file changes its URL changes,
// so the browser has to fetch it again; unchanged files stay cached.
//
//   node scripts/stamp.js           update index.html
//   node scripts/stamp.js --check   fail if index.html is out of date (used in CI)

import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const indexPath = join(root, 'index.html');

async function files(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await files(p)));
    else if (/\.(js|css)$/.test(entry.name)) out.push(p);
  }
  return out.sort();
}

const hashOf = async (p) => createHash('sha256').update(await readFile(p)).digest('hex').slice(0, 10);

const imports = {};
let cssHash = '';
for (const p of await files(join(root, 'src'))) {
  const rel = './' + relative(root, p).split('\\').join('/');
  if (p.endsWith('.css')) { if (rel === './src/styles/main.css') cssHash = await hashOf(p); continue; }
  imports[rel] = `${rel}?v=${await hashOf(p)}`;
}

const map = JSON.stringify({ imports }, null, 2).replace(/\n/g, '\n  ');
const block = `<!-- stamp:start (generated by scripts/stamp.js, do not edit) -->
<link rel="stylesheet" href="src/styles/main.css?v=${cssHash}">
<script type="importmap">
  ${map}
</script>
<script type="module">import './src/main.js';</script>
<!-- stamp:end -->`;

const html = await readFile(indexPath, 'utf8');
const re = /<!-- stamp:start[\s\S]*?<!-- stamp:end -->/;
if (!re.test(html)) throw new Error('index.html mist de stamp-markers');
const next = html.replace(re, block);

if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error('✗ index.html is niet bijgewerkt: draai `npm run stamp` en commit opnieuw.');
    process.exit(1);
  }
  console.log('✓ cache-versies in index.html kloppen');
} else {
  await writeFile(indexPath, next);
  console.log(`✓ ${Object.keys(imports).length} modules gestempeld`);
}
